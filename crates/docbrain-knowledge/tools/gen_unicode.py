"""Generate src/charset/tables.rs from the Unicode 17.0.0 Character Database.

Usage: python3 -I tools/gen_unicode.py <dir> > src/charset/tables.rs

<dir> holds DerivedGeneralCategory.txt (ucd/extracted/), PropList.txt (ucd/) and emoji-data.txt
(ucd/emoji/), downloaded as they are published. The output pins the version and each input's sha256, so a
reader can check the tables against the Consortium's files. Standard library only.
"""

import hashlib
import os
import re
import sys

VERSION = "17.0.0"
EXPECT_HEADER = {
    "DerivedGeneralCategory.txt": "# DerivedGeneralCategory-17.0.0.txt",
    "PropList.txt": "# PropList-17.0.0.txt",
    "emoji-data.txt": "# Version: 17.0",
}
LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)\s*(?:#|$)")


def read(dirname, name):
    path = os.path.join(dirname, name)
    with open(path, "rb") as f:
        data = f.read()
    text = data.decode("utf-8")
    if EXPECT_HEADER[name] not in text.splitlines()[:12]:
        sys.exit(f"{name}: header {EXPECT_HEADER[name]!r} not found; not the {VERSION} file")
    return text, hashlib.sha256(data).hexdigest()


def ranges(text, wanted):
    out = []
    for line in text.splitlines():
        m = LINE.match(line)
        if not m or not wanted(m.group(3)):
            continue
        lo = int(m.group(1), 16)
        hi = int(m.group(2), 16) if m.group(2) else lo
        out.append((lo, hi))
    out.sort()
    merged = []
    for lo, hi in out:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


def emit(name, doc, rs):
    print(f"/// {doc}")
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for lo, hi in rs:
        print(f"    (0x{lo:04X}, 0x{hi:04X}),")
    print("];")
    print()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    d = sys.argv[1]
    gc, gc_sha = read(d, "DerivedGeneralCategory.txt")
    pl, pl_sha = read(d, "PropList.txt")
    em, em_sha = read(d, "emoji-data.txt")
    print("// SPDX-License-Identifier: MIT")
    print("//! Generated by `tools/gen_unicode.py` from the Unicode Character Database; do not edit.")
    print(f"//! Unicode {VERSION}. Inputs (sha256):")
    print(f"//! - ucd/extracted/DerivedGeneralCategory.txt {gc_sha}")
    print(f"//! - ucd/PropList.txt {pl_sha}")
    print(f"//! - ucd/emoji/emoji-data.txt {em_sha}")
    print("//!")
    print("//! Each table is sorted, inclusive ranges that neither overlap nor touch.")
    print()
    print(f'pub const UNICODE_VERSION: &str = "{VERSION}";')
    print(f'pub const SHA256_DERIVED_GENERAL_CATEGORY: &str = "{gc_sha}";')
    print(f'pub const SHA256_PROP_LIST: &str = "{pl_sha}";')
    print(f'pub const SHA256_EMOJI_DATA: &str = "{em_sha}";')
    print()
    emit("CF", "General_Category=Cf (format characters).", ranges(gc, lambda v: v == "Cf"))
    emit("CC", "General_Category=Cc (the C0 and C1 controls).", ranges(gc, lambda v: v == "Cc"))
    emit("LETTER", "General_Category=L* (Lu, Ll, Lt, Lm, Lo).", ranges(gc, lambda v: v in ("Lu", "Ll", "Lt", "Lm", "Lo")))
    emit("MARK", "General_Category=M* (Mn, Mc, Me).", ranges(gc, lambda v: v in ("Mn", "Mc", "Me")))
    emit("VARIATION_SELECTOR", "Variation_Selector=Yes (PropList).", ranges(pl, lambda v: v == "Variation_Selector"))
    emit("EMOJI", "Emoji=Yes (emoji-data).", ranges(em, lambda v: v == "Emoji"))


if __name__ == "__main__":
    main()
